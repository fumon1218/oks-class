const OPTIONAL_ASSETS = ['./art/scenes/town_spring_hd.webp'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(ASSETS.map((p) => new Request(p, { cache: 'reload' }))).then(() => Promise.all(
        OPTIONAL_ASSETS.map((path) => cache.add(path).catch(() => null))
      )))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n)))
    ).then(() => self.clients.claim())
  );
});

// 브라우저·CDN 임시 저장본이 섞여 옛 파일이 보이지 않도록, 새로 받을 때는 항상 서버에 확인(no-cache·reload)합니다.
// 화면(HTML)은 항상 최신을 먼저 받아오고, 오프라인일 때만 저장본을 씀(네트워크 우선).
// 아이콘 등 잘 안 바뀌는 파일은 저장본을 먼저 씀(캐시 우선) — 그래야 배포 직후에도 바로 새 화면이 보입니다.
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const isPage = event.request.mode === 'navigate' || event.request.destination === 'document';
  // 화면 코드(js·css·json)도 최신 먼저: 고친 내용이 새로고침 한 번에 바로 보이게 (오프라인이면 저장본)
  const isCode = /\.(js|css|json)(\?|$)/.test(new URL(event.request.url).pathname) || ['script', 'style'].includes(event.request.destination);

  if (isPage || isCode) {
    event.respondWith(
      fetch(event.request, { cache: 'no-cache' })
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => caches.match(event.request).then((cached) => cached || caches.match('./index.html')))
    );
    return;
  }

  // A previously missing high-resolution image must not be stuck behind a cached 404.
  const newMap = event.request.url.includes('/art/scenes/town_spring_hd.webp');
  if(newMap){
    event.respondWith(fetch(event.request).then((response)=>{
      if(response.ok){const copy=response.clone();caches.open(CACHE_NAME).then(cache=>cache.put(event.request,copy));}
      return response;
    }).catch(()=>caches.match(event.request)));
    return;
  }
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached && cached.ok) return cached;
      return fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          if(response.ok) caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => caches.match('./index.html'));
    })
  );
});
